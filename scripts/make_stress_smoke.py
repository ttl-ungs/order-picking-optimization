"""Build scripts/stress_smoke.json: the stress tests that are cheap enough to run on every PR.

    python -m scripts.make_stress_smoke                  # tests that finished in <= 15 s
    python -m scripts.make_stress_smoke --max-seconds 5

A stress test qualifies when, in the latest recorded run of its model (results/<model>/stress/,
read through analysis.load), it finished OK within --max-seconds. Tests are matched by unittest
method name -- the same key the analysis pipeline joins on -- and a test module is included only
if every test method in it qualifies and no method name is ambiguous within the model. Only the
Hill Climbing / ACO models are listed: opp_v4/opp_v5_2_split need the zimpl binary and never converge at
stress scale.

`python -m scripts.run_all --tier stress --smoke` then runs just those files through
tests/run_suite.py (with a per-test cap), so stress tests are really executed on every PR
without waiting for the slow or unsolvable ones. Regenerate after new stress results are
recorded or stress tests are added.
"""

import argparse
import collections
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from analysis.config import STABILITY_MODELS  # noqa: E402  (the six HC/ACO models)
from analysis.load import load_all  # noqa: E402

OUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "stress_smoke.json")

LIST_CODE = """
import sys, unittest
def walk(s):
    for t in s:
        if isinstance(t, unittest.TestSuite):
            yield from walk(t)
        else:
            yield t.id()
for tid in walk(unittest.TestLoader().discover(start_dir=sys.argv[1], pattern="test_*.py")):
    print("ID", tid)
"""


def discover(model):
    """{case id (e.g. '04'): [method names]} for tests/<model>/stress."""
    out = subprocess.run([sys.executable, "-c", LIST_CODE, os.path.join("tests", model, "stress")],
                         capture_output=True, text=True, check=True).stdout
    modules = collections.defaultdict(list)
    for line in out.splitlines():
        if line.startswith("ID "):
            *_, module, class_name, method = line[3:].strip().split(".")
            case = re.match(r"(?:Case|Stress)(\d+)", class_name)
            modules[case.group(1) if case else module[len("test_case_"):]].append(method)
    return modules


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--max-seconds", type=float, default=15.0)
    args = ap.parse_args()

    df = load_all(verbose=False)
    stress = df[df["scenario"] == "stress"]
    models = {}
    for model in STABILITY_MODELS:
        rows = stress[stress["model"] == model]
        fast = set(rows[(rows["status"] == "ok") & (rows["total_time"] <= args.max_seconds)]["instance"])
        modules = discover(model)
        name_count = collections.Counter(m for methods in modules.values() for m in methods)
        ids = sorted(i for i, methods in modules.items()
                     if all(m in fast and name_count[m] == 1 for m in methods))
        models[model] = {"ids": ids, "tests": sum(len(modules[i]) for i in ids)}
        print(f"{model}: {len(ids)}/{len(modules)} stress files qualify ({models[model]['tests']} tests)")

    with open(OUT_PATH, "w", encoding="utf-8") as fh:
        json.dump({
            "_source": f"Generated by scripts/make_stress_smoke.py from the latest recorded stress runs in results/: "
                       f"tests that finished OK in <= {args.max_seconds:g} s. Regenerate instead of editing by hand.",
            "max_seconds": args.max_seconds,
            "models": models,
        }, fh, indent=1)
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
